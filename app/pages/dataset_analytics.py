"""
Exploratory Data Analysis (EDA) views.
Includes visualizations of:
    - Class Distribution (Donut & Bar)
    - Source Dataset counts
    - Email word count / length histograms
    - Word clouds (displayed as static images generated by main.py)
    - Interactive top frequent words by class
    - Correlation Heatmap of metadata features
"""

import os

import pandas as pd
import plotly.express as px
import streamlit as st
from PIL import Image

from components.theme import get_current_theme_colors
from src.config import CLEANED_DATASET_PATH, IMAGES_DIR


def show_dataset_analytics():
    """Renders the Dataset Analytics Page."""
    colors = get_current_theme_colors()

    st.markdown(
        f"""
        <h1>📊 <span class="gradient-text">Dataset Analytics</span></h1>
        <p style="color: {colors['text']}; opacity: 0.8; font-size: 1.1rem; margin-bottom: 25px;">
            Exploratory Data Analysis (EDA) of the unified training corpus.
        </p>
        """,
        unsafe_allow_html=True,
    )

    # Check for cleaned dataset
    if not os.path.exists(CLEANED_DATASET_PATH):
        st.warning(
            "⚠️ Cleaned dataset not found. Please execute the training pipeline first "
            "using main.py to generate analytical assets."
        )
        return

    # Load only the needed columns (avoids pulling the whole 550 MB CSV into RAM)
    @st.cache_data(show_spinner="Loading dataset analytics...", max_entries=1)
    def load_subset_data():
        df = pd.read_csv(
            CLEANED_DATASET_PATH,
            usecols=["text_combined", "label", "source_dataset"],
        )
        # Sample down to a representative subset for snappy UI rendering
        if len(df) > 50000:
            df = df.sample(n=50000, random_state=42)
        return df

    df = load_subset_data()

    tab_dist, tab_words, tab_features = st.tabs([
        "📈 Class & Source Distribution",
        "🔤 Text & Word Frequencies",
        "📐 Metadata & Correlations",
    ])

    with tab_dist:
        col_pie, col_source = st.columns(2)

        with col_pie:
            st.markdown("### Class Ratio Balance")
            counts = df["label"].value_counts().reset_index()
            counts.columns = ["Class", "Count"]
            counts["Class"] = counts["Class"].map({0: "Legitimate", 1: "Phishing"})

            fig_pie = px.pie(
                counts,
                values="Count",
                names="Class",
                hole=0.4,
                color="Class",
                color_discrete_map={"Legitimate": colors["legitimate"], "Phishing": colors["phishing"]},
            )
            fig_pie.update_layout(height=350, margin=dict(l=20, r=20, t=30, b=20))
            st.plotly_chart(fig_pie, width="stretch")

        with col_source:
            st.markdown("### Data Origin Distribution")
            if "source_dataset" in df.columns:
                src_counts = df["source_dataset"].value_counts().reset_index()
                src_counts.columns = ["Source Dataset", "Count"]

                fig_src = px.bar(
                    src_counts,
                    x="Count",
                    y="Source Dataset",
                    orientation="h",
                    color="Source Dataset",
                    color_discrete_sequence=px.colors.sequential.Agsunset,
                )
                fig_src.update_layout(height=350, margin=dict(l=20, r=20, t=30, b=20), showlegend=False)
                st.plotly_chart(fig_src, width="stretch")
            else:
                st.info("Source dataset information is not present in the processed file.")

    with tab_words:
        col_wc1, col_wc2 = st.columns(2)

        with col_wc1:
            st.markdown("### Legitimate Emails Wordcloud")
            wc_legit_path = os.path.join(IMAGES_DIR, "wordcloud_legitimate.png")
            if os.path.exists(wc_legit_path):
                st.image(Image.open(wc_legit_path), width="stretch")
            else:
                st.info("Legitimate wordcloud not found. Run training pipeline to generate.")

        with col_wc2:
            st.markdown("### Phishing Emails Wordcloud")
            wc_phish_path = os.path.join(IMAGES_DIR, "wordcloud_phishing.png")
            if os.path.exists(wc_phish_path):
                st.image(Image.open(wc_phish_path), width="stretch")
            else:
                st.info("Phishing wordcloud not found. Run training pipeline to generate.")

        st.markdown("---")
        st.markdown("### Top Vocabulary Terms")
        word_select = st.selectbox(
            "Select Target Class:",
            ["Phishing Emails", "Legitimate Emails", "All Emails"],
        )

        img_name = {
            "Phishing Emails": "top_words_phishing.png",
            "Legitimate Emails": "top_words_legitimate.png",
            "All Emails": "top_words_overall.png",
        }[word_select]

        tw_path = os.path.join(IMAGES_DIR, img_name)
        if os.path.exists(tw_path):
            st.image(Image.open(tw_path), width="stretch")
        else:
            st.info(f"{word_select} top words chart not found. Run training pipeline to generate.")

    with tab_features:
        st.markdown("### Email Text Length Distribution")

        df_len = df.copy()
        df_len["char_count"] = df_len["text_combined"].fillna("").str.len()
        df_len = df_len[df_len["char_count"] < df_len["char_count"].quantile(0.95)]
        df_len["Class"] = df_len["label"].map({0: "Legitimate", 1: "Phishing"})

        fig_hist = px.histogram(
            df_len,
            x="char_count",
            color="Class",
            barmode="overlay",
            opacity=0.6,
            color_discrete_map={"Legitimate": colors["legitimate"], "Phishing": colors["phishing"]},
            labels={"char_count": "Character Count"},
            nbins=80,
        )
        fig_hist.update_layout(
            height=350,
            margin=dict(l=20, r=20, t=30, b=20),
            xaxis_title="Email Length (Characters)",
            yaxis_title="Count",
        )
        st.plotly_chart(fig_hist, width="stretch")

        st.markdown("---")
        st.markdown("### Correlation of Metadata Features")

        heatmap_path = os.path.join(IMAGES_DIR, "correlation_heatmap.png")
        if os.path.exists(heatmap_path):
            st.image(Image.open(heatmap_path), width="stretch")
        else:
            st.info("Correlation Heatmap image not found. Run training pipeline to generate.")
